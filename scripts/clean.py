"""Remove caches, the vector index and (with --venv) the virtualenv."""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

TARGETS = [
    ROOT / "data" / "chroma",
    ROOT / "data" / "uploads",
    ROOT / "data" / "registry.json",
    ROOT / ".pytest_cache",
]


def remove(path: Path) -> None:
    if path.is_dir():
        shutil.rmtree(path, ignore_errors=True)
        print(f"removed {path.relative_to(ROOT)}/")
    elif path.exists():
        path.unlink()
        print(f"removed {path.relative_to(ROOT)}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Clean generated files.")
    parser.add_argument("--venv", action="store_true", help="also remove .venv")
    args = parser.parse_args()

    for target in TARGETS:
        remove(target)
    for cache in ROOT.rglob("__pycache__"):
        shutil.rmtree(cache, ignore_errors=True)
    for pdf in (ROOT / "data" / "samples").glob("*.pdf"):
        remove(pdf)  # regenerated by scripts/ingest_samples.py
    if args.venv:
        remove(ROOT / ".venv")
    print("clean")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
